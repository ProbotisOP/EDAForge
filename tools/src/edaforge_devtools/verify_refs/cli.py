"""``edaforge-verify-refs``: build, cover and verify ``docs/references.bib``.

    edaforge-verify-refs build     # section 21 + supplement -> docs/references.bib
    edaforge-verify-refs coverage  # every in-text citation has an entry
    edaforge-verify-refs verify    # check entries against Crossref / arXiv

``verify`` exits 0 when every entry is verified or has no DOI, 1 when an entry failed or needs
review, and 3 when some registry lookups could not be made (those entries are inconclusive).
``build`` and ``coverage`` read the specification and exit 2 when it is missing.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from collections.abc import Sequence
from dataclasses import asdict
from pathlib import Path

from edaforge_devtools.verify_refs.bib import parse_bib, render_bib
from edaforge_devtools.verify_refs.coverage import missing_citations
from edaforge_devtools.verify_refs.crossref import urllib_fetcher, verify_entry
from edaforge_devtools.verify_refs.spec_to_bib import entries_from_spec, load_supplement

__all__ = ["main"]

_HEADER = """References for EDAForge.
Generated by `edaforge-verify-refs build` from docs/PROJECT_PROMPT.md section 21 and
docs/references-supplement.toml. Do not edit by hand; edit those sources and rebuild.
edaforge_spec_text keeps the specification's exact citation; edaforge_status records verification.
No DOI in this file was typed from memory: DOIs are added only by `edaforge-verify-refs verify`."""


def _body(spec: str) -> str:
    return spec.split("## 21. References", 1)[0]


def _read_spec(path: str) -> str | None:
    spec = Path(path)
    if not spec.is_file():
        print(f"specification not found: {spec} (pass --spec)", file=sys.stderr)
        return None
    return spec.read_text(encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="edaforge-verify-refs")
    parser.add_argument("--spec", default="docs/archive/PROJECT_PROMPT.v1.md")
    parser.add_argument("--supplement", default="docs/references-supplement.toml")
    parser.add_argument("--bib", default="docs/references.bib")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build")
    sub.add_parser("coverage")
    verify = sub.add_parser("verify")
    verify.add_argument("--report", default="docs/references-verification.json")
    verify.add_argument("--write", action="store_true", help="record statuses in the .bib")
    args = parser.parse_args(argv)

    if args.command == "build":
        spec = _read_spec(args.spec)
        if spec is None:
            return 2
        entries = entries_from_spec(spec) + load_supplement(Path(args.supplement))
        Path(args.bib).write_text(render_bib(entries, _HEADER), encoding="utf-8")
        print(f"wrote {len(entries)} entries to {args.bib}")
        return 0
    entries = parse_bib(Path(args.bib).read_text(encoding="utf-8"))
    if args.command == "coverage":
        spec = _read_spec(args.spec)
        if spec is None:
            return 2
        missing = missing_citations(_body(spec), entries)
        for citation in missing:
            print(f"missing: {citation.authors} ({citation.year}) in {citation.context!r}")
        print(f"{len(missing)} in-text citations without an entry")
        return 1 if missing else 0
    results = [verify_entry(entry, urllib_fetcher) for entry in entries]
    counts = Counter(r.status for r in results)
    Path(args.report).write_text(
        json.dumps(
            {"counts": dict(sorted(counts.items())), "results": [asdict(r) for r in results]},
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    if args.write:
        by_key = {r.key: r for r in results}
        for entry in entries:
            result = by_key[entry.key]
            if result.status != "network_unavailable":
                entry.fields["edaforge_status"] = result.status
            if result.status == "verified" and result.doi:
                entry.fields["doi"] = result.doi
        Path(args.bib).write_text(render_bib(entries, _HEADER), encoding="utf-8")
    print(", ".join(f"{k}: {v}" for k, v in sorted(counts.items())))
    if any(r.status in {"mismatch", "not_found", "candidate"} for r in results):
        return 1
    if counts.get("network_unavailable", 0):
        print(
            f"{counts['network_unavailable']} entries could not be checked: registries unreachable",
            file=sys.stderr,
        )
        return 3
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
